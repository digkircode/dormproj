-- Существующая "Стоимость" фактически содержит цены "не из нашего вуза" (проверено
-- построчным сравнением с прайс-листом от пользователя, 2026-08-23) — переименовываем,
-- значения не трогаем (историческая protected-выгрузка остаётся как есть).
UPDATE room_characteristic_definitions SET name = 'Стоимость (не из вуза)' WHERE name = 'Стоимость';

-- Комнаты 112-2 и 410-2 — полностью посуточные (нет месячной ставки вообще, см.
-- backend/src/billing/accrual-generation.ts), их прежнее значение "Стоимость" (15000/14500,
-- не из прайс-листа) убираем, чтобы отсутствие месячной цены однозначно значило "посуточная".
DELETE FROM room_characteristic_values
WHERE definition_id = (SELECT id FROM room_characteristic_definitions WHERE name = 'Стоимость (не из вуза)')
  AND room_id IN (SELECT id FROM rooms WHERE room IN ('112-2', '410-2'));

-- Новая характеристика — цена для проживающих из своего вуза (OWN_UNIVERSITY). Protected
-- (неудаляемая через UI, как остальные стартовые характеристики), но значения НЕ protected —
-- это не историческая 1С-выгрузка, сотрудники должны иметь возможность поправить цену.
INSERT INTO room_characteristic_definitions (name, value_type, unit, is_protected, sort_order)
VALUES ('Стоимость (из вуза)', 'NUMBER', '₽', true, (SELECT COALESCE(MAX(sort_order), 0) + 1 FROM room_characteristic_definitions));

