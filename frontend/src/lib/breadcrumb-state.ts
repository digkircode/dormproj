import { ref } from 'vue'

// Детальные страницы (карточка договора, физлица и т.п.) переопределяют заголовок
// последней крошки на что-то конкретное (номер договора, имя физлица) вместо статичного
// meta.title из router/index.ts — иначе крошки показывают не то, где реально находишься
// ("Информация о договоре" для любого договора), а просто название страницы вообще.
// Каждая детальная страница выставляет значение при загрузке данных и сбрасывает в null
// при размонтировании (см. App.vue, где это подставляется в последнюю крошку).
export const breadcrumbOverride = ref<string | null>(null)
